#!/usr/bin/env bash
# Создаёт issues по docs/BACKLOG-ANDROID.md.
#
# Зачем скрипт, а не «агент создал issues сам»: в workflow claude.yml агенту не
# разрешён `gh`, поэтому issues создаёт человек одной командой. Скрипт
# идемпотентен по заголовку: если issue с таким же title уже есть (в любом
# состоянии), он пропускается — можно доливать задачи повторными запусками.
#
# Требования: gh CLI, авторизованный на этот репозиторий (`gh auth login`).
#
# Использование (бит +x не выставлен — запускать через bash):
#   DRY_RUN=1 bash scripts/create-backlog-issues.sh      # показать, что будет создано
#   bash scripts/create-backlog-issues.sh                # создать всё
#   EPICS="E0 E1" bash scripts/create-backlog-issues.sh  # только выбранные эпики
#
# Сначала прогоните с DRY_RUN=1 — скрипт не проверялся запуском (в CI-окружении
# агенту не разрешены ни `gh`, ни `bash -n`).

set -euo pipefail

REPO="${REPO:-jack5505/mahalla-android}"
DRY_RUN="${DRY_RUN:-0}"
EPICS="${EPICS:-}"
BACKLOG_URL="https://github.com/${REPO}/blob/main/docs/BACKLOG-ANDROID.md"

DOD='### Definition of Done
- [ ] Код + unit-тесты в одном коммите (правило проекта, `AGENTS.md`)
- [ ] `./gradlew testDebugUnitTest` — зелёный, вывод в PR
- [ ] `./gradlew assembleDebug` — зелёный
- [ ] Экран/компонент сверен с прототипом в light и dark, ru и uz
- [ ] Строки — в `values/strings.xml` (uz) и `values-ru/strings.xml`, не в коде'

ensure_labels() {
  local specs=(
    "epic:E0-foundation:0e8a16"
    "epic:E1-onboarding:1d76db"
    "epic:E2-discovery:1d76db"
    "epic:E3-food:1d76db"
    "epic:E4-queue:1d76db"
    "epic:E5-booking:1d76db"
    "epic:E6-wallet:1d76db"
    "epic:E7-subscription:1d76db"
    "epic:E8-profile:1d76db"
    "epic:E9-business:1d76db"
    "epic:E10-quality:5319e7"
    "P0:d73a4a" "P1:e99695" "P2:fbca04" "P3:c2e0c6"
    "android:c5def5" "blocker:b60205"
  )
  local spec name color
  for spec in "${specs[@]}"; do
    name="${spec%:*}"
    color="${spec##*:}"
    if [[ "$DRY_RUN" == "1" ]]; then
      echo "  [dry-run] label: $name"
    else
      gh label create "$name" --repo "$REPO" --color "$color" >/dev/null 2>&1 || true
    fi
  done
}

# mk <epic-label> <priority> <extra-labels|-> <title> <body>
mk() {
  local epic="$1" prio="$2" extra="$3" title="$4" body="$5"

  if [[ -n "$EPICS" ]]; then
    local want matched=0
    for want in $EPICS; do
      [[ "$epic" == "epic:${want}-"* ]] && matched=1
    done
    [[ "$matched" == "1" ]] || return 0
  fi

  if gh issue list --repo "$REPO" --state all --search "\"$title\" in:title" \
      --json title --jq '.[].title' | grep -Fxq "$title"; then
    echo "  = пропуск (уже есть): $title"
    return 0
  fi

  local labels="$epic,$prio,android"
  if [[ "$extra" != "-" ]]; then
    labels="$labels,$extra"
  fi

  local full_body
  full_body="$body

$DOD

---
Из backlog'а: [docs/BACKLOG-ANDROID.md](${BACKLOG_URL}) · родительская задача: #1"

  if [[ "$DRY_RUN" == "1" ]]; then
    echo "  + [dry-run] $title  [$labels]"
    return 0
  fi

  gh issue create --repo "$REPO" --title "$title" --body "$full_body" --label "$labels"
}

echo "Репозиторий: $REPO (DRY_RUN=$DRY_RUN)"
echo "Метки:"
ensure_labels
echo "Задачи:"

