package uz.mahalla.core.result

/**
 * Что именно ответил бэкенд на неуспешный запрос (issue #34).
 *
 * До этого тело ответа выбрасывалось: HTTP-код превращался в один из вариантов
 * [ApiError], и человек видел «Bu amal uchun ruxsat yo'q» там, где сервер
 * прислал подробное объяснение («включите доступ к геолокации, вот как это
 * сделать»). Настоящую причину приходилось искать в инспекторе трафика.
 *
 * Поэтому ответ доезжает до UI целиком: [message] — текст для человека,
 * [code] — машинный код для поддержки, [body] и [requestLine] — раскрываемые
 * подробности «куда ходили и что получили».
 */
data class ServerError(
    /** HTTP-код ответа. */
    val httpCode: Int,
    /** Статус-строка HTTP («Forbidden»), если сервер её прислал. */
    val httpMessage: String? = null,
    /** Машинный код ошибки бэкенда, например `GEO_PERMISSION_REQUIRED`. */
    val code: String? = null,
    /** Текст для пользователя из тела ответа. */
    val message: String? = null,
    /** Метод и адрес запроса: `POST https://api.mahalla.uz/auth/otp/request`. */
    val requestLine: String? = null,
    /** Тело ответа для показа целиком; JSON переформатирован с отступами. */
    val body: String? = null,
) {
    /** Есть ли текст, который осмысленно показать вместо общей заглушки. */
    val hasMessage: Boolean get() = !message.isNullOrBlank()
}

/**
 * Отказ запроса целиком: [error] — классификация для логики (ветвление,
 * фоллбэк на кэш, разлогин), [server] — то, что сказал сервер, для показа
 * пользователю.
 *
 * Две части раздельно, потому что у них разные потребители: логике нужен
 * стабильный набор вариантов, а человеку — конкретный текст. Смешивание
 * (например, `ApiError.Forbidden(message)`) сломало бы сравнения по значению,
 * на которых держатся `asOtpFailure`, фоллбэк каталога и тесты.
 *
 * [server] равен null, когда ответа не было вовсе: нет сети, таймаут,
 * исключение до отправки.
 */
data class ApiFailure(
    val error: ApiError,
    val server: ServerError? = null,
) {
    /** Текст бэкенда, если он вообще прислал непустой. */
    val serverMessage: String? get() = server?.message?.takeIf { it.isNotBlank() }
}
