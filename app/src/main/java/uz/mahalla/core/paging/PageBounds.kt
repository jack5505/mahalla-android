package uz.mahalla.core.paging

/**
 * Есть ли у страничного ответа следующая страница.
 *
 * Одно правило на все страничные ручки бэкенда: у них у всех один конверт
 * `PageResponse…` (`content` / `page` / `size` / `totalElements` /
 * `totalPages` / `first` / `last`), и считать конец списка по-разному в
 * каждой вертикали незачем. До issue #142 это правило лежало четырьмя
 * копиями — у заказов одежды, у мастеров, у кошелька и в «моих активностях»,
 * — и копии уже начали расходиться.
 *
 * Приоритет у `last`: его считает сервер, и он единственный знает про
 * последнюю страницу наверняка. Без него смотрим на номер страницы и
 * `totalPages`. Полное молчание сервера о страницах останавливает догрузку:
 * лучше не показать хвост списка, чем зациклить запрос одной и той же
 * страницы (issue #62).
 *
 * @param page номер страницы, относительно которой считаем. Там, где он
 * известен из запроса, передаётся **запрошенный**, а не пришедший: сервер,
 * не вернувший `page`, отдаёт дефолтный `0`, и «следующей» навсегда осталась
 * бы первая.
 */
fun hasMorePages(page: Int?, totalPages: Int?, last: Boolean?): Boolean = when {
    last != null -> !last
    totalPages != null -> (page ?: 0) + 1 < totalPages
    else -> false
}
