package uz.mahalla.core.format

/**
 * Единица денег бэкенда (issue #149).
 *
 * Бэкенд задокументировал это в `info.description` живого `/v3/api-docs`
 * (2026-09-10): **все целые денежные поля приходят и уходят в тийинах**,
 * 1 сум = 100 тийинов, дробные значения и суммы в сумах он не принимает. До
 * этого ответа приложение считало те же поля сумами и рисовало цены в сто раз
 * больше настоящих — «5 000 000 so'm» за стрижку.
 *
 * Правило одно на весь проект: **домен, экраны и Room живут в целых сумах**,
 * а пересчёт делается ровно один раз — в маппере DTO → домен ([tiyinToSom]) и
 * в обратную сторону при сборке тела запроса ([somToTiyin]). Ни экран, ни
 * ViewModel единицу бэкенда знать не должны — иначе делитель расползётся по
 * коду, и следующая вертикаль снова «забудет» его применить.
 *
 * Поля с дробным близнецом (`balanceSom`, `monthlyPriceSom`) бэкенд отдаёт для
 * удобства, и раньше единица **выводилась** из этой пары (`WalletAmounts`).
 * После ответа бэкенда вывод не нужен: близнец игнорируется, делитель — сто.
 */
object Money {

    /** 1 сум = 100 тийинов. */
    const val TIYIN_IN_SOM = 100L

    /**
     * Тийины → целые сумы, половина округляется от нуля (`150` → `2`,
     * `149` → `1`, `-150` → `-2`).
     *
     * Цены на стенде кратны сотне, так что округление — страховка от мусора в
     * поле, а не рабочий путь. Считается целыми, без `Double`: у сумм порядка
     * миллиардов тийинов плавающая точка ещё точна, но и повода её звать нет.
     * Отрицательные суммы (списания в истории кошелька) округляются
     * симметрично положительным, чтобы `+150` и `-150` в одной истории не
     * расходились по величине.
     */
    fun tiyinToSom(tiyin: Long): Long {
        val half = TIYIN_IN_SOM / 2
        return if (tiyin >= 0) (tiyin + half) / TIYIN_IN_SOM else -((-tiyin + half) / TIYIN_IN_SOM)
    }

    /** То же для необязательного поля: `null` остаётся `null`. */
    fun tiyinToSom(tiyin: Long?): Long? = tiyin?.let(::tiyinToSom)

    /**
     * Целые сумы → тийины для тела запроса (`TopUpRequest.amount` и любые
     * будущие поля с деньгами, которые шлёт клиент).
     */
    fun somToTiyin(som: Long): Long = Math.multiplyExact(som, TIYIN_IN_SOM)
}

/** `price?.tiyinToSom()` — короткая форма [Money.tiyinToSom] для мапперов. */
fun Long.tiyinToSom(): Long = Money.tiyinToSom(this)

/** `null` остаётся `null`; иначе как [Long.tiyinToSom]. */
fun Long?.tiyinToSom(): Long? = Money.tiyinToSom(this)
