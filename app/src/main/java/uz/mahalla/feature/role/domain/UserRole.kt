package uz.mahalla.feature.role.domain

/**
 * Кем человек пользуется приложением (issue #84).
 *
 * Ролей ровно две, и они не про права доступа — их выдаёт бэкенд, — а про то,
 * какую анкету человек заполняет: потребитель услуг или тот, кто их оказывает.
 * Одно другому не мешает: владелец кафе сам заказывает еду, поэтому роль
 * переключается в любой момент и ничего не запирает.
 *
 * Домен без Android: подписи берутся из ресурсов в UI-слое (как у `City` и
 * `AppLanguage`), чтобы список работал на обоих языках и тестировался на JVM.
 *
 * [storedValue] — то, что лежит в DataStore. Имя константы туда не пишем:
 * переименование `Customer` в коде не должно стирать выбор пользователя.
 */
enum class UserRole(val storedValue: String) {
    /** Покупатель: ищет и заказывает услуги. */
    Customer("customer"),

    /** Продавец: оказывает услуги, регистрирует заведение. */
    Provider("provider"),
    ;

    companion object {
        /**
         * `null` — роль ещё не выбрана. Это нормальное состояние: анкету можно
         * пропустить, и приложение работает как раньше.
         *
         * Незнакомое значение — тоже `null`, а не «покупатель»: настройка
         * могла приехать из будущей версии приложения, и врать о выборе
         * человека хуже, чем спросить заново.
         */
        fun fromStoredValue(value: String?): UserRole? {
            val raw = value?.trim().orEmpty()
            if (raw.isEmpty()) return null
            return entries.firstOrNull { it.storedValue.equals(raw, ignoreCase = true) }
        }
    }
}
