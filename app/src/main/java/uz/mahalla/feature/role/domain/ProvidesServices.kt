package uz.mahalla.feature.role.domain

/**
 * Оказывает ли человек услуги — одно правило на всё приложение (issue #244).
 *
 * Условий два, потому что и источника два, и они про разное (issue #237):
 * анкета ([UserRole.Provider]) — это заявка, её человек заполняет сам и может
 * не заполнить вовсе; серверная роль ([ServerRole.isProvider]) — право, его
 * выдаёт админ, и приложение на него не влияет. Настоящий `FOOD_OWNER` без
 * анкеты — обычный случай, и не увидеть из-за него своё заведение или свои
 * тарифы человек не должен.
 *
 * Цена ошибки несимметрична: ложное «да» — это пустой список заведений и
 * набор тарифов, который не подойдёт (человек вернётся и переключит роль);
 * ложное «нет» — спрятанный бизнес, о котором человек не узнает. Поэтому
 * «или», а не «и».
 *
 * Функция, а не свойство какого-то одного состояния: правило спрашивают из
 * разных мест — `ProfileState.showMyPlaces` (строка «Мои заведения») и
 * `RoleProfile.providesServices` (аудитория тарифов подписки), — и две копии
 * разошлись бы. Один раз уже разошлись: строка в профиле спрашивала оба
 * источника, а подписки — только анкету.
 *
 * @param formRole роль из анкеты; `null` — анкету не заполняли.
 * @param serverRole права с сервера; [ServerRole.Unknown] — входа ещё не было
 * либо роль незнакомая.
 */
fun providesServices(formRole: UserRole?, serverRole: ServerRole): Boolean =
    formRole == UserRole.Provider || serverRole.isProvider
