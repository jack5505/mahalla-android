package uz.mahalla.data.network.inspector

import android.content.Intent
import okhttp3.Interceptor

/**
 * Инспектор HTTP-трафика (issue #30): показывает, какие запросы уходят на
 * бэкенд — адрес, метод, query-параметры, заголовки, тело запроса и ответа.
 *
 * За интерфейсом он ради двух вещей: сетевой слой не зависит от конкретной
 * библиотеки (сегодня Chucker, завтра что угодно), а тесты подставляют свою
 * реализацию и проверяют, что инспектор действительно стоит в цепочке и видит
 * запрос в том виде, в каком он уходит в сеть.
 */
interface HttpInspector {

    /**
     * Доступен ли инспектор в этой сборке. В release приезжает no-op-вариант
     * библиотеки: интерцептора нет, экрана нет, строки в профиле нет.
     */
    val isAvailable: Boolean

    /**
     * Интерцептор для OkHttp или `null`, если инспектор недоступен: в
     * магазинной сборке лишнего звена в цепочке быть не должно.
     */
    val interceptor: Interceptor?

    /** Экран со списком запросов или `null`, если инспектор недоступен. */
    fun launchIntent(): Intent?
}
