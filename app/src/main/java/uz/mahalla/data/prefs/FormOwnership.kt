package uz.mahalla.data.prefs

/**
 * Чья анкета лежит на устройстве — роль и адрес доставки (issue #84, #243).
 *
 * Выход анкету не стирает: «забыли PIN» и лимит попыток тоже идут через
 * выход, и тот же человек, войдя заново, заполнял бы её с начала. Вместо
 * этого анкета помнит `id` аккаунта и достаётся только ему. Иначе после входа
 * под другим номером в оформление заказа подставлялся бы адрес прежнего
 * человека, и заказ уехал бы не туда.
 *
 * Город сюда не входит: он про место, а не про человека.
 *
 * За интерфейсом — ради тестов входа: им DataStore не нужен.
 */
interface FormOwnership {

    /**
     * Вход завершён под аккаунтом [userId]: анкета другого аккаунта
     * стирается, своя остаётся.
     *
     * `null` — сервер аккаунт не назвал. Такая анкета считается чужой, как и
     * анкета без известного владельца (заполненная до issue #243): заполнить
     * анкету лишний раз дешевле, чем отправить заказ на чужой адрес.
     */
    suspend fun claimFor(userId: String?)
}
